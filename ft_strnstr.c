#include "libft.h"

char	*ft_strnstr(const char *big, const char *little, size_t len)
{
	size_t	i;
	size_t	j;

	i = 0;
	if (little[0] == '\0')
		return ((char *)big);
	while (big[i] != '\0' && i < len)
	{
		j = 0;
		while (little[j] != '\0' && i + j < len && little[j] == big[i + j])
			j++;
		if (j == ft_strlen(little))
			return (&((char *)big)[i]);
		i++;
	}
	return (NULL);
}
